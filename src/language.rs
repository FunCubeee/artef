pub fn line_comment(language: Language) -> Option<&'static str> {
    match language {
        Language::Python | Language::Shell | Language::Yaml | Language::Toml => Some("#"),
        Language::JavaScript
        | Language::TypeScript
        | Language::Rust
        | Language::C
        | Language::Cpp
        | Language::Go => Some("//"),
        Language::Json | Language::Markdown | Language::Plain => None,
    }
}

pub fn block_comment(language: Language) -> Option<(&'static str, &'static str)> {
    match language {
        Language::JavaScript
        | Language::TypeScript
        | Language::Rust
        | Language::C
        | Language::Cpp
        | Language::Go => Some(("/*", "*/")),
        _ => None,
    }
}

pub fn hash_comment_needs_space(language: Language) -> bool {
    matches!(language, Language::Shell)
}
